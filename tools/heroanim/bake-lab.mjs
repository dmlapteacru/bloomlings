// Isolated original-motion experiment. Reuses the production renderer and bounded palette-frame path.
// node tools/heroanim/bake-lab.mjs; models/sprig-lab.glb is authored by author-lab.py.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { PNG } from 'pngjs';
import { serve } from './serve.mjs';
import { palette, indexed, writePng8 } from './png8.mjs';
import { sha256 } from './bake.mjs';

const here = path.dirname(fileURLToPath(import.meta.url)), repo = path.resolve(here,'../..');
const out = path.join(repo,'playtest/art/HeroLab');
const review = path.join(repo,'content/work/hero-lab/review');
fs.mkdirSync(out,{recursive:true});fs.mkdirSync(review,{recursive:true});
const config = JSON.parse(fs.readFileSync(path.join(here,'heroes.json')));
const source = config.heroes.find(h=>h.family==='sprig');
const {server,port} = await serve();
let browser;
try {
  browser = await chromium.launch({executablePath:process.env.HERO_LAB_CHROMIUM || undefined,
    args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
  const page = await browser.newPage({viewport:{width:256,height:288}});
  page.on('pageerror',e=>console.error(e.message));
  await page.goto(`http://127.0.0.1:${port}/page.html`);
  await page.waitForFunction(()=>window.ready);
  console.log('Rendering four authored Sprig motions on a shared camera...');
  const job = {file:'sprig-lab.glb',mesh:source.mesh,idle:'Lab_Sprig_Idle',react:'Lab_Sprig_Hello',
    win:['Lab_Sprig_Look','Lab_Sprig_Bow','Lab_Sprig_Bounce'],head:source.head,top:source.top,
    topOffset:source.topOffset,ground:'model',fps:20,idleSeconds:.05,reactSeconds:3,
    idleBlend:.4,reactIn:.15,reactOut:.2,yaw:0,pitch:config.pitch,fov:config.fov,
    light:config.light,color:source.color,cell:[256,288],feet:.9,fill:.78,margin:.025,width:512,height:576};
  const result = await page.evaluate(j=>window.bake(j),job);
  const names={idle:'idle',react:'hello',win:'look',win2:'bow',win3:'bounce'};
  const counts={},frames=[];
  for(const f of result.frames) {
    const clip=names[f.clip];
    if(clip==='idle'&&counts.idle)continue;
    const i=counts[clip]??0;counts[clip]=i+1;
    const png=PNG.sync.read(Buffer.from(f.png.split(',')[1],'base64'));
    const name=`lab-sprig-${clip}-${String(i).padStart(2,'0')}`;
    fs.mkdirSync(path.join(review,clip),{recursive:true});
    fs.writeFileSync(path.join(review,clip,`${String(i).padStart(2,'0')}.png`),PNG.sync.write(png));
    let x0=png.width,y0=png.height,x1=-1,y1=-1;
    for(let y=0;y<png.height;y++)for(let x=0;x<png.width;x++)if(png.data[(y*png.width+x)*4+3]){
      x0=Math.min(x0,x);y0=Math.min(y0,y);x1=Math.max(x1,x);y1=Math.max(y1,y);
    }
    if(x1<0||x0<4||y0<4||x1>=png.width-4||y1>=png.height-4)throw new Error(name+': empty/clipped frame');
    const crop=new PNG({width:x1-x0+1,height:y1-y0+1});
    for(let y=0;y<crop.height;y++)png.data.copy(crop.data,y*crop.width*4,((y+y0)*png.width+x0)*4,((y+y0)*png.width+x1+1)*4);
    frames.push({name,clip,crop:[x0,y0,crop.width,crop.height],head:f.head.map((v,i)=>v/job.cell[i]),
      top:f.top.map((v,i)=>v/job.cell[i]),picture:crop});
  }
  console.log('Quantizing',frames.length,'frames with one shared palette...');
  const pal=palette(frames.map(f=>f.picture),128);
  for(const f of frames){const p=f.picture;const bytes=writePng8(p.width,p.height,indexed(p,pal),pal);
    fs.writeFileSync(path.join(out,f.name+'.png'),bytes);delete f.picture;f.bytes=bytes.length;f.sha256=sha256(bytes);}
  const table=['idle','look','hello','bow','bounce'].map(clip=>frames.filter(f=>f.clip===clip));
  const lines=['// Generated by tools/heroanim/bake-lab.mjs. Experimental clips; production heroes are unchanged.',
    'namespace Bloomlings.Client.UI.Design','{','    public static partial class HeroLab', '    {',
    '        public const int Fps = 20, CellWidth = 256, CellHeight = 288;',
    '        private static readonly HeroLabFrame[][] Frames = new HeroLabFrame[][]','        {'];
  for(const group of table){lines.push('            new HeroLabFrame[]','            {');for(const f of group)
    lines.push(`                new HeroLabFrame("${f.name}", ${f.crop.join(', ')}, ${[...f.head,...f.top].map(n=>n.toFixed(6)+'f').join(', ')}),`);
    lines.push('            },');}
  lines.push('        };','    }','}');
  const data='client/Assets/Bloomlings/UI/Design/HeroLabData.cs';
  fs.writeFileSync(path.join(repo,data),lines.join('\n')+'\n');
  const manifest={tool:'tools/heroanim/bake-lab.mjs',source:'tools/heroanim/models/sprig-lab.glb',
    sourceSha256:sha256(fs.readFileSync(path.join(here,'models/sprig-lab.glb'))),data,
    dataSha256:sha256(fs.readFileSync(path.join(repo,data))),fps:20,cell:job.cell,counts,
    files:frames.map(f=>({path:f.name+'.png',width:f.crop[2],height:f.crop[3],slot:'ui.hero_lab',source:'owner',
      sha256:f.sha256,bytes:f.bytes,record:'tools/heroanim/LAB.md'})),frames};
  fs.writeFileSync(path.join(out,'manifest.json'),JSON.stringify(manifest,null,1)+'\n');
  console.log('Hero lab:',frames.length,'frames,',frames.reduce((a,f)=>a+f.bytes,0),'bytes.');
} finally { if(browser)await browser.close();server.close(); }
